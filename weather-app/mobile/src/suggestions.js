// Hàm cấp phát ảnh độc nhất 100% cho 6 thẻ đề xuất
export function resolveUniqueCardImages(suggestions, seed) {
  const usedImages = new Set();
  return suggestions.slice(0, 6).map((item, idx) => {
    const pool = LIFESTYLE_PHOTO_POOLS[item.photoCategory] || [];
    let chosenImg = null;

    // 1. Lựa chọn trong pool của category theo seed và index
    if (pool.length > 0) {
      for (let i = 0; i < pool.length; i++) {
        const candidate = pool[(seed + idx + i) % pool.length];
        if (!usedImages.has(candidate)) {
          chosenImg = candidate;
          break;
        }
      }
    }

    // 2. Nếu pool đã bị sử dụng hết, chọn từ danh sách fallback độc nhất
    if (!chosenImg) {
      for (const fb of DEDICATED_FALLBACK_IMAGES) {
        if (!usedImages.has(fb)) {
          chosenImg = fb;
          break;
        }
      }
    }

    // 3. Dự phòng bất khả kháng
    if (!chosenImg) {
      const base = pool.length > 0 ? pool[0] : DEDICATED_FALLBACK_IMAGES[0];
      chosenImg = `${base}&uid=${seed}-${idx}`;
    }

    usedImages.add(chosenImg);
    return {
      ...item,
      image: chosenImg,
    };
  });
}

